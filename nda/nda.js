/* ================= ТИПОГРАФ (код, править не нужно) =================
   Склеивает неразрывным пробелом короткие слова со следующим (предлоги, союзы),
   частицы и тире — с предыдущим, числа — с единицами. Так на узком экране
   «в», «и», «на» не остаются висеть в конце строки. */
var NV_SHORT = 'а|в|и|к|о|с|у|я|во|да|до|за|из|ко|на|не|ни|но|об|от|по|со|то|для|без|при|над|под|про|или|что|как|это|его|все|еще|их|ее|мы|вы|он|она|они';
var NV_RX_SHORT = new RegExp('(^|[\\s«„"(\\u00A0])(' + NV_SHORT + ')[ ]+', 'gi');
function nvTypo(t){
  if(!t || typeof t !== 'string') return t;
  for(var i = 0; i < 2; i++) t = t.replace(NV_RX_SHORT, '$1$2 ');          /* «и в» подряд */
  t = t.replace(/[ ]+(же|ли|бы)(?=[\s.,!?:;»]|$)/gi, ' $1');                  /* частицы — к слову перед ними */
  t = t.replace(/[ ]+(—|–)(?=[ ])/g, ' $1');                                  /* тире не начинает строку */
  t = t.replace(/(\d)[ ](?=\d{3}(?!\d))/g, '$1 ');                            /* 50 000 */
  t = t.replace(/(\d)[ ]+(₽|%|млн|млрд|тыс\.?|руб\.?|лет|года?|дн(ей|я)?|час(а|ов)?|мин)/g, '$1 $2');
  return t;
}
/* то же для уже готовой страницы: проходит по всем текстам внутри root */
function nvTypoDom(root){
  if(!root) return;
  var w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, { acceptNode: function(n){
    var p = n.parentNode && n.parentNode.nodeName; return (p === 'SCRIPT' || p === 'STYLE' || p === 'TEXTAREA') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT; } });
  var n; while((n = w.nextNode())){ var v = nvTypo(n.nodeValue); if(v !== n.nodeValue) n.nodeValue = v; }
}

